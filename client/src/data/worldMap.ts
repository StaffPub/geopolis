/**
 * GEOPOLIS — Géographie locale des 36 entités du monde alternatif.
 * Polygones [lon, lat] simplifiés, projection équirectangulaire vers le
 * viewBox SVG. Aucune API cartographique externe : tout est embarqué.
 */

export type LonLat = [number, number];

export interface RegionShape {
  id: string;
  polygons: LonLat[][];
}

export const MAP_WIDTH = 1000;
export const MAP_HEIGHT = 520;

export function project([lon, lat]: LonLat): [number, number] {
  const x = ((lon + 180) / 360) * MAP_WIDTH;
  const y = ((90 - lat) / 180) * MAP_HEIGHT;
  return [x, y];
}

export function polygonToPath(poly: LonLat[]): string {
  if (poly.length === 0) return '';
  const pts = poly.map(project);
  let d = `M ${pts[0]![0].toFixed(1)} ${pts[0]![1].toFixed(1)}`;
  for (let i = 1; i < pts.length; i++) {
    d += ` L ${pts[i]![0].toFixed(1)} ${pts[i]![1].toFixed(1)}`;
  }
  return d + ' Z';
}

export function regionCentroid(shape: RegionShape): [number, number] {
  const poly = shape.polygons.reduce((a, b) => (a.length >= b.length ? a : b), [] as LonLat[]);
  let x = 0;
  let y = 0;
  for (const p of poly) {
    const [px, py] = project(p);
    x += px;
    y += py;
  }
  return [x / Math.max(1, poly.length), y / Math.max(1, poly.length)];
}

